const DAY = 86_400_000

/** ISO timestamp `days` from today at a fixed hour (stable for hydration). */
function inDays(days: number, hour = 10): string {
  const date = new Date()
  date.setHours(hour, 0, 0, 0)
  date.setDate(date.getDate() + days)
  return date.toISOString()
}

/** Mid-month timestamp relative to the current month. */
function monthOffset(offset: number, day = 12): string {
  const now = new Date()
  return new Date(now.getFullYear(), now.getMonth() + offset, day, 12).toISOString()
}

